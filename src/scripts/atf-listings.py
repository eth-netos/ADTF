#!/usr/bin/env python3
"""Regenerates the objdump listings in src/lean/ADTF/AtfLibc/Listing.

Each file Listing/<fn>_o.lean stands for the function <fn>. The script
builds BL31 (build-bl31.py), finds the object file that defines <fn>, and
overwrites the file with objdump's listing of <fn>. To add a function,
create an empty Listing/<fn>_o.lean and rerun the script. Afterwards,
`git diff` shows what changed."""

import importlib.util
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("build_bl31",
                                              HERE / "build-bl31.py")
build_bl31 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build_bl31)

LISTING_DIR = build_bl31.ROOT / "src" / "lean" / "ADTF" / "AtfLibc" / "Listing"

TEMPLATE = '''module

-- Generated by src/scripts/atf-listings.py. Do not edit; rerun the script.

/-- `{cmd}`,
run in `imx-atf/build/imx93/release`. -/
@[expose] public def {fn}_o_dump : String := r#"{dump}"#
'''


def run(cmd):
    return subprocess.run(cmd, cwd=build_bl31.BUILD_DIR, check=True,
                          capture_output=True, text=True).stdout


def function_definitions():
    """Maps each function symbol to the object files that define it."""
    objs = sorted(p.relative_to(build_bl31.BUILD_DIR).as_posix()
                  for p in build_bl31.BUILD_DIR.rglob("*.o"))
    defs = {}
    obj = None
    for line in run([build_bl31.tool("readelf"), "-sW"] + objs).splitlines():
        if line.startswith("File: "):
            obj = line[len("File: "):]
            continue
        fields = line.split()
        if (len(fields) == 8 and fields[3] == "FUNC"
                and fields[6] != "UND"):
            defs.setdefault(fields[7], []).append(obj)
    return defs


def main():
    build_bl31.build()
    fns = sorted(p.name[:-len("_o.lean")]
                 for p in LISTING_DIR.glob("*_o.lean"))
    defs = function_definitions()
    for fn in fns:
        objs = defs.get(fn, [])
        if len(objs) != 1:
            sys.exit(f"error: {fn} must be defined by exactly one object "
                     f"file, found: {objs}")
        cmd = [build_bl31.tool("objdump"), "-d", "-r",
               f"--disassemble={fn}", objs[0]]
        dump = run(cmd)
        if dump.count(f"\n0000000000000000 <{fn}>:\n") != 1:
            sys.exit(f"error: objdump printed no listing of {fn}")
        if '"#' in dump:
            sys.exit(f'error: the listing of {fn} contains "#')
        shown = " ".join(["aarch64-none-elf-objdump"] + cmd[1:])
        (LISTING_DIR / f"{fn}_o.lean").write_text(
            TEMPLATE.format(cmd=shown, fn=fn, dump=dump))


if __name__ == "__main__":
    main()
